# ── 结尾（直接接在最后，带标点）
ENDS = ["", "", "", "", "", "", "", "", "", "", "", "", "", "", "",
        "。", "。", "。", "。", "。", "。。。", "……", "…"]

# 极少数才有的收尾（占比很低，不是每句都有）
ENDS_RARE = ["算了。", "睡吧。", "明天还播。", "写下来好受一点。"]


def fill(s):
    for k, vals in V.items():
        ph = "{%s}" % k
        while ph in s:
            s = s.replace(ph, random.choice(vals), 1)
    return s


def build():
    ev = fill(random.choice(EVENTS))

    # 30% 加一句感慨
    if random.random() < 0.30:
        fl = fill(random.choice(FEELS))
        # 两句之间必须有句号
        body = ev.rstrip("。") + "。" + fl
    else:
        body = ev

    # 结尾标点：绝大多数只有标点，不写总结句
    if random.random() < 0.05:
        end = random.choice(ENDS_RARE)
    else:
        end = random.choice(ENDS)
    if not end:
        if not body.endswith(("。", "…")):
            body = body + "。"
    elif end.startswith(("。", "…")):
        # 纯标点，直接接（"。。。" 这种真人就这么打）
        body = body.rstrip("。") + end
    else:
        # 完整短句：必须先把前一句收尾
        body = body.rstrip("。") + "。" + end

    return body.strip()


