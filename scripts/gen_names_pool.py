# -*- coding: utf-8 -*-
"""生成 999 个网名感昵称（用于留言 / 回复的人名）。

为什么要这个：
  原来回复昵称是从 8 个固定名字里 random.choice，
  一条留言下抽 2~3 个，跨留言还接着抽 → 屏幕上「三点零七」出现两三次，一眼假。

生成规则（拼得像真人取的网名）：
  前缀 60 个 × 主体 110 个 = 6600 种 → 洗牌取 999，几乎不会撞
  + 少量「时间型」「数字型」网名（三点零七 / 十一点四十 / 阿蓝_0912）
"""
import json, io, random, sys
sys.stdout.reconfigure(encoding="utf-8")
random.seed(20261116)

PRE = ["阿", "小", "老", "半", "不", "大", "旧", "新", "夜", "晚", "清", "冷", "暖",
       "甜", "酸", "咸", "淡", "浅", "深", "空", "轻", "慢", "快", "懒", "困", "醒",
       "睡", "醒", "雨", "风", "云", "月", "星", "灯", "茶", "酒", "糖", "盐",
       "橘", "柚", "桃", "李", "梅", "竹", "松", "柏", "石", "土", "木", "水",
       "江", "河", "海", "湖", "山", "岭", "谷", "野", "城", "乡", "巷", "街"]

BODY = ["柚", "橘", "桃", "梨", "栗", "梅", "竹", "松", "柏", "禾", "苗", "麦",
        "灯", "船", "歌", "弦", "琴", "鼓", "钟", "铃", "箫", "笛",
        "月", "星", "云", "风", "雨", "雪", "霜", "雾", "光", "影", "烟", "尘",
        "猫", "狗", "兔", "鹿", "鱼", "鸟", "鹅", "鸭", "熊", "狼", "狐", "鹤",
        "糖", "茶", "酒", "盐", "醋", "粥", "汤", "面", "包", "糕", "饼", "果",
        "秋", "冬", "春", "夏", "晚", "早", "夜", "昼", "晨", "暮", "昏", "夕",
        "心", "梦", "念", "思", "忆", "眠", "醒", "醉", "痴", "傻", "呆", "憨",
        "七", "九", "三", "五", "十", "百", "千", "零", "半", "满", "空", "缺",
        "白", "黑", "灰", "青", "蓝", "紫", "粉", "橙", "绿", "红", "黄", "褐"]

SUF = ["", "", "", "", "", "", "", "", "", "", "", "",
       "呀", "呢", "吧", "啊", "酱", "同学", "本人", "本猫", "不睡", "失眠",
       "的猫", "的鱼", "的灯", "的船", "的糖", "的雨", "的月",
       "不说话", "不加班", "在等", "还没睡", "困了", "起不来",
       "_0912", "_07", "_11", "_23", "_0713", "_1129", "_0101"]

# 时间型（这类最像真人）
TIMES = ["三点零七", "十一点四十七", "十二点零五", "两点十七", "四点零八",
         "一点二十三", "五点零六", "九点半", "十点十分", "七点四十",
         "凌晨两点", "凌晨四点", "半夜三点", "下午三点"]

pool, seen = set(), set()

# ① 时间型
for t in TIMES:
    if t not in seen:
        seen.add(t); pool.add(t)

# ② 前缀 + 主体 + 后缀
combos = []
for a in PRE:
    for b in BODY:
        for s in SUF:
            combos.append(a + b + s)
random.shuffle(combos)

for name in combos:
    if len(pool) >= 999:
        break
    if len(name) < 2 or len(name) > 9:
        continue
    if name in seen:
        continue
    seen.add(name)
    pool.add(name)

# ③ 兜底（万一个数不够）
i = 0
while len(pool) < 999 and i < 10000:
    i += 1
    n = "阿%s%02d" % (random.choice(BODY), i)
    if n not in seen:
        seen.add(n); pool.add(n)

out = sorted(pool)
io.open("scripts/names_pool.json", "w", encoding="utf-8").write(
    json.dumps(out, ensure_ascii=False, separators=(",", ":")))

print("昵称池:", len(out), "个")
print("样例:", out[:20])
print("随机抽 10:", random.sample(out, 10))
