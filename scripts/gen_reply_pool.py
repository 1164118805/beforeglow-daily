# ── 变体后缀（只加一个，且不叠字）
SUF = ["", "", "", "啊", "呀", "吧", "了", "哦", "呢", "…"]
PRE = ["", "", "", "哎，", "唉，", "说真的，"]


def add(w, suf):
    if suf and w and w[-1] == suf[0]:
        return w
    return w + suf


def grow(items, target):
    """用后缀/前缀把一批句子扩到 target 条，保证不重复。"""
    out, seen = [], set()
    for w in items:
        if w not in seen:
            seen.add(w); out.append(w)
    rounds = 0
    while len(out) < target and rounds < 40:
        rounds += 1
        for w in items:
            s = add(w, SUF[rounds % len(SUF)])
            if s not in seen:
                seen.add(s); out.append(s)
            if len(out) >= target:
                break
            if rounds % 3 == 0:
                s2 = PRE[(rounds // 3) % len(PRE)] + w
                if s2 not in seen:
                    seen.add(s2); out.append(s2)
            if len(out) >= target:
                break
    return out


pool = []
for kind, items in TOPIC.items():
    # 无意义和阴阳：原样，少量
    if kind in ("none", "snark"):
        for w in items:
            pool.append({"t": w, "k": kind})
        continue
    # 其它主题：本组句子扩到 150，再掺 40% 通用牌
    grown = grow(items, 110)
    for w in grown:
        pool.append({"t": w, "k": kind})
    common_n = int(len(grown) * 0.4)
    for w in grow(COMMON, common_n if common_n else 40):
        pool.append({"t": w, "k": kind})

